function convertWordToHtml(wordFilePath: string) {
  return new Promise((resolve, reject) => {
    Mammoth
      .convertToHtml({ path: wordFilePath })
      .then((result) => {
        resolve(result.value); // HTML内容
      })
      .catch((err) => {
        reject(err);
      });
  });
};

function extractImageUrls(html: any) {
  const $ = load(html);
  const imageUrls = [] as string[];
  $("img").each((i, img) => {
    const src = $(img).attr("src");
    if (src) {
      imageUrls.push(src);
    }
  });
  return imageUrls;
};

